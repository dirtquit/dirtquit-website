export function getCategoryBySlug(slug: string): CategoryData | undefined {
  const normalized = (slug || "").toLowerCase().trim();
  return CATEGORIES.find(
    (c) =>
      c.slug === normalized ||
      c.id === normalized ||
      // Legacy id aliases
      (normalized === "move-cleaning" && c.slug === "move-in-move-out-cleaning") ||
      (normalized === "post-construction" && c.slug === "post-construction-cleaning") ||
      (normalized === "regular-cleaning" && c.slug === "regular-home-cleaning"),
  );
}
